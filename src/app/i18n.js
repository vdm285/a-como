let lang = 'es';
export function setLang(l) { lang = STR[l] ? l : 'es'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, vars) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// ---- formatting (locale-aware, MXN) ----
const mxn = { es: new Intl.NumberFormat('es-MX', { style: 'currency', currency: 'MXN', maximumFractionDigits: 2 }), en: new Intl.NumberFormat('en-US', { style: 'currency', currency: 'MXN', currencyDisplay: 'narrowSymbol', maximumFractionDigits: 2 }) };
export function money(v, opts = {}) {
  if (v == null || !Number.isFinite(v)) return '—';
  const f = mxn[lang] || mxn.es;
  let s = f.format(v);
  if (opts.compact && Math.abs(v) >= 1000) s = s.replace(/\.00$/, '');
  return s;
}
export function pct(v, digits = 0) {
  if (v == null || !Number.isFinite(v)) return '—';
  const sign = v > 0 ? '+' : v < 0 ? '−' : '';
  return `${sign}${Math.abs(v * 100).toFixed(digits)} %`;
}
const dateFmt = { es: new Intl.DateTimeFormat('es-MX', { day: 'numeric', month: 'short', year: 'numeric' }), en: new Intl.DateTimeFormat('en-US', { day: 'numeric', month: 'short', year: 'numeric' }) };
const dateShort = { es: new Intl.DateTimeFormat('es-MX', { day: 'numeric', month: 'short' }), en: new Intl.DateTimeFormat('en-US', { day: 'numeric', month: 'short' }) };
export function fdate(iso, short = false) {
  if (!iso) return '—';
  const d = new Date(iso + (iso.length === 10 ? 'T12:00:00' : ''));
  if (Number.isNaN(d.getTime())) return iso;
  return (short ? dateShort : dateFmt)[lang].format(d);
}
export function unitName(unit) {
  return { l: t('perL'), kg: t('perKg'), '100g': t('per100g'), '100ml': t('per100ml'), pza: t('perPza') }[unit] || unit;
}
