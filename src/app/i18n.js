let lang = 'es';
export function setLang(l) { lang = STR[l] ? l : 'es'; if (typeof document !== 'undefined') document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, vars) {
  if (vars && vars.n === 1) { const one = `${key.replace(/_n$/, '')}_1`; if ((STR[lang] && STR[lang][one]) || STR.es[one]) key = one; }
  let s = (STR[lang] && STR[lang][key]) ?? STR.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// ---- formatting (locale-aware, MXN) ----
const mxn = { es: new Intl.NumberFormat('es-MX', { style: 'currency', currency: 'MXN', maximumFractionDigits: 2, minimumFractionDigits: 2 }), en: new Intl.NumberFormat('en-US', { style: 'currency', currency: 'MXN', currencyDisplay: 'narrowSymbol', maximumFractionDigits: 2, minimumFractionDigits: 2 }) };
export function money(v) {
  if (v == null || !Number.isFinite(v)) return '—';
  return (mxn[lang] || mxn.es).format(v);
}
export function pct(v, digits = 0) {
  if (v == null || !Number.isFinite(v)) return '—';
  const sign = v > 0.00049 ? '+' : v < -0.00049 ? '−' : '';
  return `${sign}${Math.abs(v * 100).toFixed(digits)} %`;
}

let dataYear = String(new Date().getFullYear());
export function setDataYear(y) { if (y) dataYear = String(y); }
const loc = () => (lang === 'en' ? 'en-US' : 'es-MX');
const cache = new Map();
const fmt = (opts) => { const k = `${lang}|${JSON.stringify(opts)}`; if (!cache.has(k)) cache.set(k, new Intl.DateTimeFormat(loc(), { timeZone: 'UTC', ...opts })); return cache.get(k); };
const clean = (s) => s.replace(/\./g, '').replace(/ de /g, ' ');
function parse(iso) { const d = new Date(`${iso.slice(0, 10)}T12:00:00Z`); return Number.isNaN(d.getTime()) ? null : d; }
export function fdate(iso, mode = false) {
  if (!iso) return '—';
  const d = parse(iso);
  if (!d) return iso;
  const y = iso.slice(0, 4);
  if (mode === 'month') return clean(fmt({ month: 'short' }).format(d));
  if (mode === 'monthYear') return clean(fmt({ month: 'short', year: 'numeric' }).format(d));
  if (mode === true && y === dataYear) return clean(fmt({ day: 'numeric', month: 'short' }).format(d));
  return clean(fmt({ day: 'numeric', month: 'short', year: 'numeric' }).format(d));
}
// a date range in the fewest words: "4–31 ago 2026", "28 jul – 24 ago 2026", "30 dic 2025 – 5 ene 2026"
export function fspan(from, to, short = false) {
  if (!from || !to) return fdate(from || to);
  if (from === to) return fdate(to, short);
  const a = parse(from), b = parse(to);
  if (!a || !b) return `${from} – ${to}`;
  const yA = from.slice(0, 4), yB = to.slice(0, 4);
  const showYear = !(short && yB === dataYear);
  if (yA !== yB) return `${fdate(from)} – ${fdate(to)}`;
  if (from.slice(0, 7) === to.slice(0, 7)) {
    const day = (d) => fmt({ day: 'numeric' }).format(d);
    return `${day(a)}–${day(b)} ${clean(fmt({ month: 'short' }).format(b))}${showYear ? ' ' + yB : ''}`;
  }
  const dm = (d) => clean(fmt({ day: 'numeric', month: 'short' }).format(d));
  return `${dm(a)} – ${dm(b)}${showYear ? ' ' + yB : ''}`;
}
// unit names: "litro" / short "L"
export function unitName(unit, short = false) {
  if (short) return { l: 'L', kg: 'kg', '100g': '100 g', '100ml': '100 ml', pza: lang === 'en' ? 'pc' : 'pza' }[unit] || unit || '';
  return { l: t('perL'), kg: t('perKg'), '100g': t('per100g'), '100ml': t('per100ml'), pza: t('perPza') }[unit] || unit || '';
}
